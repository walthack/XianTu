#!/usr/bin/env node

// Deterministically turns source-axis events plus cached DeepSeek outline reviews
// into runtime profiles. Existing hand-reviewed stages stay in canonRail.ts.

import { existsSync, readdirSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const gen = join(root, 'mod-kit', 'generated', 'deepseek-v4-flash');
const stagesDir = join(root, 'src', 'modules', 'scenarioMods', 'builtins', 'data');
const reviewDir = join(gen, 'character-canon', 'canon-rail', 'all-stages-review');
const out = join(root, 'src', 'modules', 'scenarioMods', 'canonRailProfiles.generated.ts');
const rollup = join(reviewDir, 'PROFILE-ROLLUP.md');
const manualStageIds = new Set(['lcq.stage_01', 'lcq.stage_02']);
// This legacy freeform draft has no source-axis facts at all. It must stay out
// of the default route until it is rebuilt from anchored source material.
const quarantinedUnanchoredStageIds = new Set(['lyl.taiquan_expedition']);
const isCritical = event => event.critical !== undefined ? event.critical === true
  : event.axisMethod !== 'reviewed-no-anchor' && event.axisId !== null
    && Boolean(event.axisBeat || event.axisId || typeof event.axisSeq === 'number');
const sanitizeTerms = value => Array.isArray(value)
  ? value.map(item => String(item || '').replace(/\s+/g, '').slice(0, 12)).filter(item => item.length >= 2).slice(0, 4)
  : [];
function fallbackEvidence(event, beat) {
  const fromName = String(event.name || '').match(/[\u4e00-\u9fff]{2,8}/g) || [];
  const fromBeat = String(beat || '').match(/[\u4e00-\u9fff]{2,8}/g) || [];
  return [...new Set([...fromName, ...fromBeat])].slice(0, 3);
}
const binding = JSON.parse(await readFile(join(gen, 'character-canon', 'axis-binding.json'), 'utf8'));
const axisById = new Map((binding.nodes || []).map(node => [node.axisId, node]));
const reviews = new Map();
await mkdir(reviewDir, { recursive: true });
if (existsSync(reviewDir)) {
  for (const file of readdirSync(reviewDir).filter(file => file.endsWith('.deepseek-v4.json'))) {
    const artifact = JSON.parse(await readFile(join(reviewDir, file), 'utf8'));
    reviews.set(artifact.target?.stageId, artifact.review || {});
  }
}
const profiles = [];
for (const file of readdirSync(stagesDir).filter(file => file.endsWith('.json')).sort()) {
  const mod = JSON.parse(await readFile(join(stagesDir, file), 'utf8'));
  const stageId = mod.manifest?.id;
  if (!stageId || manualStageIds.has(stageId)) continue;
  const review = reviews.get(stageId) || {};
  const reviewed = new Map((review.events || []).filter(item => item?.id).map(item => [item.id, item]));
  const originalOrder = new Map((mod.scenario?.events || []).map((event, index) => [event.id, index]));
  const events = (mod.scenario?.events || []).filter(isCritical).slice().sort((a, b) => {
    const aSeq = axisById.get(a.axisId)?.seq ?? a.axisSeq ?? Infinity;
    const bSeq = axisById.get(b.axisId)?.seq ?? b.axisSeq ?? Infinity;
    return aSeq - bSeq || (originalOrder.get(a.id) ?? 0) - (originalOrder.get(b.id) ?? 0);
  });
  if (!events.length) {
    if (!quarantinedUnanchoredStageIds.has(stageId)) {
      throw new Error(`${stageId} has no source-anchored critical events; add an explicit quarantine decision or repair its source bindings.`);
    }
    continue;
  }
  const contracts = events.map(event => {
    const axis = axisById.get(event.axisId);
    const sourceBeat = axis?.beat || event.axisBeat || event.description || event.name;
    const model = reviewed.get(event.id) || {};
    const mustReach = typeof model.mustReach === 'string' && model.mustReach.trim() ? model.mustReach.trim() : sourceBeat;
    const evidence = sanitizeTerms(model.completionEvidence);
    return {
      eventId: event.id,
      mustReach,
      completionEvidence: evidence.length ? evidence : fallbackEvidence(event, sourceBeat),
      forbiddenInCanon: sanitizeTerms(model.forbiddenInCanon).length ? sanitizeTerms(model.forbiddenInCanon) : ['改写本拍原著结果', '提前演出后续剧情'],
      allowedElaboration: typeof model.allowedElaboration === 'string' && model.allowedElaboration.trim()
        ? model.allowedElaboration.trim() : '可补足场景、对话、即时行动与相邻拍点之间的过渡。',
    };
  });
  profiles.push({
    id: `${stageId.replace(/^lcq\./, 'qingyu.').replace(/^lyl\./, 'yunlong.').replace(/^lyg\./, 'yange.')}`,
    modId: stageId,
    chapterId: mod.scenario?.chapters?.[0]?.id || `${stageId}.chapter`,
    orderedEventIds: events.map(event => event.id),
    contracts,
  });
}
const header = `/** Generated by scripts/build-canon-rail-profiles.mjs; do not hand-edit. */\nimport type { CanonRailProfile } from './canonRail';\n\n`;
await writeFile(out, `${header}export const GENERATED_CANON_RAIL_PROFILES: CanonRailProfile[] = ${JSON.stringify(profiles, null, 2)};\n`);
const contractCount = profiles.reduce((n, p) => n + p.contracts.length, 0);
await writeFile(rollup, `# Canon Rail profile rollup\n\n- 范围：所有带 source-axis 锚点的内置 stage；只使用非成人的结构化剧情摘要，不向模型发送原文正文。\n- 自动接入：${profiles.length} 个 stage，${contractCount} 个承重拍（另有 2 个手工复核的试点 stage）。\n- 顺序：每个 stage 依 source-axis seq 排列；运行时优先此序，不服从旧生成稿中互相交错的章节分组。\n- 已缓存 DeepSeek V4 复核：${reviews.size} 个 stage（只作辅助，不会直接覆盖正典）。\n- 隔离：${[...quarantinedUnanchoredStageIds].join('、')}；其事件无 source-axis 锚点，不能进入默认线。\n`);
console.log(JSON.stringify({ out, rollup, profiles: profiles.length, quarantinedUnanchoredStageIds: [...quarantinedUnanchoredStageIds], stagesWithDeepSeekReview: reviews.size, contracts: contractCount }, null, 2));
