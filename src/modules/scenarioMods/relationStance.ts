/**
 * 关系姿态渲染合同（R3-9 G1）——`voiceCards` / `intimacyProfiles` 的姊妹模块。
 *
 * 规格：docs/R3-9-AFFINITY-LADDER-SPEC-2026-08-14.md §5
 * 数值来源：`affinityLadder`（本模块不自带任何阈值）。
 *
 * 核心公式（路线图 R3-9）：
 *   角色反应 = 既有角色画像／阶段人格（稳定底色） × 对玩家的关系姿态（动态修饰） × 当前情境
 *
 * **关系只改变人物如何对待玩家，不改变人物是谁。** 因此本模块：
 *   · 只输出五个受限维度的调整方向，维度集合与路线图声明逐字一致，不自行增列；
 *   · 不碰人格底色、动机锚、权力位、正典边界与知识门禁——那些由角色档案与各自门禁负责；
 *   · 不是第二套事实引擎：事件成败、关系值增减、知识权限仍由既有引擎与结构化命令裁定。
 *
 * 反面约束同等重要：高好感 ≠ 无条件服从或泛用温柔化，低好感 ≠ 失去智性或泛用恶女化。
 * 三档去掉显式亲疏措辞后，仍须能认出是同一个人——这是 G2 的验收判据之一。
 */

